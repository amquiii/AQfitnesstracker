st.title("About Fitness Tracker App")

st.markdown("""
**App Overview**  
The Fitness Tracker application enables users to monitor and manage their daily health and fitness activities, including steps taken, workouts, sleep patterns, calorie consumption, and water intake. The app also provides visualizations of weekly progress, encouraging users to maintain a healthier and more active lifestyle.

**Target Users:**  
This application is designed for students, beginners, and anyone seeking a straightforward and engaging way to track their fitness activities.

**Inputs Collected:**  
- Name, Age, Gender  
- Daily steps, calories, sleep hours, water intake  
- Workout types and mood

**Outputs Shown:**  
- Daily summaries of activity and health metrics
- Weekly charts illustrating trends in steps, calories, and workout distribution
- Key metrics to monitor and evaluate progress over time


""")